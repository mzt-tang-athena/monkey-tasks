/**
 * Build `src/components/ui/glyphs.ts` from Phosphor's def files. Every
 * glyph keeps the box it had where it first appeared, so swapping the
 * drawing does not move layout. A new glyph is one line in `GLYPHS`
 * below, then `npm run icons:build`.
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";

/** Where `@phosphor-icons/react` keeps one module per glyph. */
export const DEFS = "node_modules/@phosphor-icons/react/dist/defs";

/** The table the app draws from: app name, Phosphor name, and the box. */
const GLYPHS = {
  list: { phosphor: "List", size: 20 },
  calendar: { phosphor: "CalendarDot", size: 20 },
  journal: { phosphor: "Notebook", size: 20 },
  inbox: { phosphor: "Tray", size: 20 },
  "calendar-mini": { phosphor: "CalendarDot", size: 11 },
  "clock-mini": { phosphor: "Clock", size: 11 },
  plus: { phosphor: "Plus", size: 18 },
  sort: { phosphor: "SortDescending", size: 20 },
  more: { phosphor: "DotsThreeVertical", size: 20 },
  rows: { phosphor: "Rows", size: 14 },
  pill: { phosphor: "Pill", size: 16 },
  repeat: { phosphor: "ArrowClockwise", size: 11 },
  grip: { phosphor: "DotsSixVertical", size: 15 },
  "grip-bars": { phosphor: "Equals", size: 10 },
  settings: { phosphor: "Gear", size: 18 },
  "chevron-right": { phosphor: "CaretRight", size: 10 },
  "chevron-down": { phosphor: "CaretDown", size: 10 },
  bell: { phosphor: "Bell", size: 14 },
  note: { phosphor: "Note", size: 14 },
  close: { phosphor: "X", size: 13 },
  check: { phosphor: "Check", size: 10 },
} as const;

type Weight = "regular" | "fill";

/**
 * One weight's drawing from a def module, or null when the module has
 * no such weight. Each weight holds its own `path`, and a glyph may
 * draw more than one, so the drawings join into one path.
 */
function drawing(source: string, weight: Weight): string | null {
  const start = source.indexOf(`"${weight}",`);
  if (start < 0) {
    return null;
  }
  const next = source.indexOf('\n  [\n    "', start);
  const block = source.slice(start, next < 0 ? undefined : next);
  const paths = [...block.matchAll(/d: "([^"]+)"/g)].map((match) => match[1]);
  return paths.length === 0 ? null : paths.join(" ");
}

/** The pair of drawings for one Phosphor glyph. */
function readGlyph(defs: string, phosphor: string): { regular: string; fill: string } {
  const source = readFileSync(join(defs, `${phosphor}.es.js`), "utf8");
  const regular = drawing(source, "regular");
  const fill = drawing(source, "fill");
  if (regular == null || fill == null) {
    throw new Error(`${phosphor} has no ${regular == null ? "regular" : "fill"} drawing`);
  }
  return { regular, fill };
}

/** The text of `glyphs.ts` for the table above. */
export function buildGlyphTable(defs: string): string {
  const entries = Object.entries(GLYPHS).map(([name, glyph]) => {
    const paths = readGlyph(defs, glyph.phosphor);
    return [
      `  ${JSON.stringify(name)}: {`,
      `    size: ${glyph.size},`,
      `    regular: ${JSON.stringify(paths.regular)},`,
      `    fill: ${JSON.stringify(paths.fill)},`,
      "  },",
    ].join("\n");
  });
  return [
    "/**",
    " * Generated by `scripts/icons/cli.ts` from @phosphor-icons/react's def",
    " * files. Do not edit it by hand: `scripts/icons/build.test.ts` fails",
    " * when it drifts from the package.",
    " *",
    " * Geometry from Phosphor Icons (https://phosphoricons.com), MIT",
    " * Licence, copyright (c) 2020 Phosphor Icons. Each drawing sits on the",
    " * 256 grid; the renderer scales it to the glyph's box. The regular",
    " * weight is the outline drawing, the fill weight the solid one.",
    " */",
    "",
    "export type GlyphDrawing = {",
    "  /** The box the glyph keeps where it first appears, in points. */",
    "  size: number;",
    "  /** The outline drawing. */",
    "  regular: string;",
    "  /** The solid drawing. */",
    "  fill: string;",
    "};",
    "",
    "export const GLYPHS = {",
    ...entries,
    "} as const satisfies Record<string, GlyphDrawing>;",
    "",
    "export type GlyphName = keyof typeof GLYPHS;",
    "",
  ].join("\n");
}
