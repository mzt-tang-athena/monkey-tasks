/**
 * Build `src/lib/vault/sample/index.ts` from the sample notes beside it
 * (ticket 0051). Metro cannot import a `.md` file as text, so the notes
 * reach the app as one generated map: seed, then path, then text.
 *
 * Each folder under the sample folder is a seed. A seed holds a vault
 * as it sits on disk, so `npm run vault:check` reads it as it is.
 */

import { readFileSync, readdirSync } from "node:fs";
import { join, relative, sep } from "node:path";

/** The sample folder, relative to `app/`. */
export const SAMPLE_DIR = "src/lib/vault/sample";

/** Every markdown file under `dir`, as sorted paths relative to it. */
function notesUnder(dir: string, root = dir): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        return notesUnder(full, root);
      }
      return entry.isFile() && entry.name.endsWith(".md")
        ? [relative(root, full).split(sep).join("/")]
        : [];
    })
    .sort();
}

/** The text of `index.ts` for the seeds in `sampleDir`. */
export function buildSampleIndex(sampleDir: string): string {
  const seeds = readdirSync(sampleDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const lines = [
    "// Generated by `npm run sample:build` from the notes beside this",
    "// file. Do not edit it: a test fails when it is out of date.",
    "",
    "export const sampleNotes: Record<string, Record<string, string>> = {",
  ];
  for (const seed of seeds) {
    lines.push(`  ${JSON.stringify(seed)}: {`);
    for (const path of notesUnder(join(sampleDir, seed))) {
      const text = readFileSync(join(sampleDir, seed, path), "utf8");
      lines.push(`    ${JSON.stringify(path)}:`, `      ${JSON.stringify(text)},`);
    }
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}
